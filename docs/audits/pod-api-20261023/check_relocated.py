#!/usr/bin/env python3
"""Qualify native generation from a fresh same-volume root containing spaces."""
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parents[3]
assert Path.cwd().resolve() == root
spec = importlib.util.spec_from_file_location('pod_reference', root / 'scripts/generate_pod_reference.py')
api = importlib.util.module_from_spec(spec)
spec.loader.exec_module(api)
temporary = root / '.artifacts/tmp'
temporary.mkdir(parents=True, exist_ok=True)
logs = root / '.artifacts/pod-api/relocated'
logs.mkdir(parents=True, exist_ok=True)


def identities(directory):
    return {p.relative_to(directory).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in directory.rglob('*') if p.is_file()}


with tempfile.TemporaryDirectory(prefix='POD reference space ', dir=temporary) as name:
    fixture = Path(name)
    assert fixture.stat().st_dev == root.stat().st_dev
    for path in (*api.TOOLS, 'scripts/mdbook_pod_api.py', 'docs/book/book.toml'):
        target = fixture / path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / path, target)
    for path in (root / 'perl/FSM').rglob('*.pm'):
        assert path.is_file() and not path.is_symlink()
        target = fixture / path.relative_to(root)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    source = fixture / 'docs/book/src'
    source.mkdir()
    (source / 'SUMMARY.md').write_text('# Summary\n\n- [Embedding](11-extensions-and-embedding.md)\n')
    (source / '11-extensions-and-embedding.md').write_text(
        '# Embedding\n\n[Generated API index](perl-api/index.html).\n')

    def build(label, cwd, arguments=(), success=True, diagnostic=None):
        result = subprocess.run(['mdbook', 'build', *arguments], cwd=cwd, capture_output=True)
        (logs / (label + '.stdout')).write_bytes(result.stdout)
        (logs / (label + '.stderr')).write_bytes(result.stderr)
        assert (result.returncode == 0) == success, (label, result.stderr.decode(errors='replace'))
        if diagnostic:
            assert diagnostic in result.stderr, (label, result.stderr.decode(errors='replace'))

    build('fresh-root', fixture, ['docs/book'], diagnostic=b'pod-reference: generated')
    generated = source / 'perl-api'
    assert identities(generated) == identities(root / api.OUTPUT), 'Relocation changed generated bytes'
    built = fixture / 'docs/book/book/perl-api'
    assert identities(built) == identities(generated)
    initial = identities(generated)
    build('book-cwd', fixture / 'docs/book', diagnostic=b'pod-reference: current')
    assert identities(generated) == initial and identities(built) == initial
    bad = fixture / 'perl/FSM/Adapter/ISF.pm'
    original = bad.read_bytes()
    bad.write_bytes(original + b'\n=head1 CONTROL\n\nE<missing>\n')
    build('malformed-refusal', fixture / 'docs/book', success=False, diagnostic=b'Malformed POD')
    assert identities(generated) == initial and identities(built) == initial
    bad.write_bytes(original)
    missing = generated / 'FSM/Adapter/ISF.html'
    missing.unlink()  # Exact generated member in this test-owned disposable fixture.
    build('missing-refusal', fixture / 'docs/book', success=False, diagnostic=b'incomplete or modified')
    assert identities(built) == initial
    repair = subprocess.run(['python3', '-B', 'scripts/generate_pod_reference.py', '--repair'],
                            cwd=fixture, capture_output=True)
    assert repair.returncode == 0, repair.stderr.decode(errors='replace')
    build('repaired-build', fixture / 'docs/book', diagnostic=b'pod-reference: current')
    assert identities(generated) == initial and identities(built) == initial
    evidence = {'same_volume': True, 'root_contains_spaces': True,
                'fresh_native_generation': True, 'root_and_book_cwd': True,
                'complete_relocated_and_copied_byte_identity': True,
                'malformed_and_missing_output_refused': True,
                'previous_source_and_built_output_retained_on_refusal': True,
                'explicit_owned_repair_restored_original_bytes': True,
                'reference_members': len(initial)}
assert not fixture.exists(), 'Disposable fixture was not removed'
evidence['exact_test_owned_workspace_removed'] = True
print(json.dumps(evidence, indent=2, sort_keys=True))
