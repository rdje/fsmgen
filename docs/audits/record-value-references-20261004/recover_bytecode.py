"""Capture/verify/remove only this slice's generated sealed-directory caches."""
import hashlib
import importlib.util
import json
import marshal
import struct
from pathlib import Path

BASE = Path(__file__).parent
directory = Path('docs/audits/record-value-scopes-20261004')
manifest = json.loads((directory / 'manifest.json').read_text())
assert {p.name for p in directory.iterdir()} == set(manifest) | {'manifest.json', '__pycache__'}
cache = directory / '__pycache__'
assert {p.name for p in cache.iterdir()} == {'model.cpython-314.pyc', 'source_recipes.cpython-314.pyc'}
records = []
for name in ('model', 'source_recipes'):
    source_path = directory / (name + '.py')
    source = source_path.read_bytes()
    assert {'bytes': len(source), 'sha256': hashlib.sha256(source).hexdigest()} == manifest[source_path.name]
    path = cache / (name + '.cpython-314.pyc')
    raw = path.read_bytes()
    assert raw[:4] == importlib.util.MAGIC_NUMBER
    flags, timestamp, size = struct.unpack('<III', raw[4:16])
    assert flags == 0 and timestamp == int(source_path.stat().st_mtime) and size == len(source)
    code = marshal.loads(raw[16:])
    assert code.co_filename == str(Path.cwd() / source_path)
    assert code == compile(source, code.co_filename, 'exec'), 'exact compiled immutable project source, never foreign/user data'
    records.append({'path': str(path), 'source': str(source_path), 'source_manifest': manifest[source_path.name],
        'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest(), 'raw_hex': raw.hex(),
        'header': {'flags': flags, 'source_mtime': timestamp, 'source_bytes': size},
        'compiled_source_equal': True})
target = BASE / 'generated-bytecode-recovery.json'
target.write_text(json.dumps(records, sort_keys=True, indent=2) + '\n')
saved = json.loads(target.read_text())
assert saved == records
for row in saved:
    raw = bytes.fromhex(row['raw_hex'])
    assert len(raw) == row['bytes'] and hashlib.sha256(raw).hexdigest() == row['sha256']
for row in saved:
    path = Path(row['path'])
    assert path.read_bytes() == bytes.fromhex(row['raw_hex'])
    path.unlink()
cache.rmdir()
assert {p.name for p in directory.iterdir()} == set(manifest) | {'manifest.json'}
for name, row in manifest.items():
    raw = (directory / name).read_bytes()
    assert {'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest()} == row
print('PASS exactly two generated bytecode files copied/byte-hash-verified as exact compiled immutable project source, removed from sealed archive, residue absent and every original sealed member unchanged. Initial archive-blocked controls remain unqualified; rerun intended semantic controls with -B.')
