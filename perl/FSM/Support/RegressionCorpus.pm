sub regression_corpus_entries {
    return map { _copy_entry($_) } @REGRESSION_CORPUS;
}

sub protocol_fixture_entries {
    return map { _copy_entry($_) } grep { $_->{family} eq 'protocol_fixture' } @REGRESSION_CORPUS;
}

sub _copy_entry {
    my ($entry) = @_;

    return _clone_entry_value($entry);
}

sub _clone_entry_value {
    my ($value) = @_;
    return undef unless defined $value;

    if (ref($value) eq 'HASH') {
        return {
            map { $_ => _clone_entry_value($value->{$_}) } sort keys %{$value}
        };
    }

    if (ref($value) eq 'ARRAY') {
        return [ map { _clone_entry_value($_) } @{$value} ];
    }

    return $value;
}

